const assert = require('node:assert/strict');
const { fitRect, uvToCanvas, meshUVSpan, trimRange, trimDraft, zoomForFit, decorationDomain, frameForMode, activeStandee, newestJobs, jobFeedback, elapsedLabel, exportTrim, renderPreferences, estimateLabel, jobResultLabel, accelerationLabel } = require('./ui-core.js');
assert.deepEqual(renderPreferences({quality:'high',renderer:'gpu',encoder:'h264_qsv'}), {renderer:'gpu',encoder:'h264_qsv'});
assert.deepEqual(renderPreferences({quality:'high'}), {renderer:'auto',encoder:'auto'});
assert.deepEqual(renderPreferences({quality:'master',renderer:'gpu',encoder:'h264_nvenc'}), {renderer:'blender',encoder:'auto'});
const budget = estimateLabel({limit_bytes:500000000,target_bytes:480000000,budget_bitrate:18000000,frames:6000,duration:200,enforced:true},'high');
assert.match(budget,/480 MB/); assert.match(budget,/严格小于 500 MB/); assert.match(budget,/18\.00 Mbps/); assert.match(budget,/6000 帧/);
assert.match(estimateLabel(null,'master'),/不执行.*500 MB/);
assert.match(estimateLabel(null,'master'),/不供 KANALI/);
assert.equal(jobResultLabel({backend:{renderer:'gpu',encoder:'h264_nvenc'},delivery:{size_bytes:248125000}}), 'GPU 加速 · NVIDIA NVENC · 248.13 MB');
assert.match(accelerationLabel({gpu:{available:false},encoders:{libx264:{available:true}}}), /回退.*Blender.*CPU H.264/);
assert.match(accelerationLabel({gpu:{available:true},encoders:{h264_nvenc:{available:true}}}), /GPU.*NVIDIA NVENC/);
assert.deepEqual(jobFeedback({status:'preparing',progress:0,phase_progress:.42}), {label:'准备素材 42%',progress:.42,active:true});
assert.deepEqual(jobFeedback({status:'preparing',phase:'verify',progress:.15,phase_progress:.7}), {label:'校验中间文件 70%',progress:.7,active:true});
assert.deepEqual(jobFeedback({status:'preparing',progress:0}), {label:'准备素材…',progress:null,active:true});
assert.deepEqual(jobFeedback({status:'rendering',progress:.33,phase_progress:.9}), {label:'渲染中 · 33%',progress:.33,active:true});
assert.deepEqual(jobFeedback({status:'preparing',phase_progress:0}), {label:'准备素材 0%',progress:0,active:true});
assert.deepEqual(jobFeedback({status:'preparing',phase_progress:2}), {label:'准备素材 100%',progress:1,active:true});
assert.deepEqual(jobFeedback({status:'failed',phase_progress:1,progress:.5}), {label:'失败',progress:null,active:false});
assert.deepEqual(jobFeedback({status:'cancelled',progress:.5}), {label:'已取消',progress:null,active:false});
assert.equal(elapsedLabel(125), '已用时 2 分 5 秒');
assert.equal(elapsedLabel(0), '已用时 0 秒');
assert.equal(elapsedLabel(undefined), '');
assert.equal(activeStandee({fit:'cover',presentation:'standee'}), false);
assert.equal(activeStandee({fit:'contain',presentation:'standee'}), true);
assert.equal(activeStandee({fit:'contain',presentation:'plain'}), false);
assert.deepEqual(newestJobs([{id:'old',created:1},{id:'new',created:3},{id:'mid',created:2}]).map(j=>j.id), ['new','mid','old']);
assert.deepEqual(fitRect(1000, 500, 1), {x:250,y:0,width:500,height:500});
assert.deepEqual(uvToCanvas([0,1], {x:10,y:20,width:200,height:100}), [10,20]);
assert.deepEqual(uvToCanvas([1,0], {x:10,y:20,width:200,height:100}), [210,120]);
const span = meshUVSpan([[0.1,-0.5],[0.8,1.5]]);
assert.ok(Math.abs(span[0] - 0.7) < 1e-12);
assert.equal(span[1], 2);
assert.deepEqual(trimRange(12, 4, 10), {start:10,end:10});
assert.deepEqual(trimRange(2, 7, 10), {start:2,end:7});
const decimalTrim = trimDraft('2.1', '7.3', 10);
assert.equal(decimalTrim.valid, true);
assert.ok(Math.abs(decimalTrim.duration - 5.2) < 1e-12);
assert.deepEqual(trimDraft('', '7.3', 10), {valid:false,duration:null});
assert.deepEqual(trimDraft('3', '2', 10), {valid:false,duration:null});
assert.deepEqual(trimDraft('0', '11', 10), {valid:false,duration:null});
assert.deepEqual(trimDraft('-1', '3', 10), {valid:false,duration:null});
const sourceDuration = 207.09166666666667;
assert.equal(trimDraft('0', sourceDuration.toFixed(3), sourceDuration).valid, true);
assert.deepEqual(exportTrim('0', '207.092', sourceDuration), {start:0,end:sourceDuration});
assert.deepEqual(exportTrim('2', '7.3', 10), {start:2,end:7.3});
assert.equal(exportTrim('0', '207.093', sourceDuration), null);
assert.equal(exportTrim('0', '10.0005', 10).end, 10);
assert.equal(exportTrim('0', '10.00051', 10), null);
assert.equal(exportTrim('0', (1/60).toFixed(3), 1/60).end, 1/60);
assert.equal(exportTrim('10', '10.0005', 10), null); // Clamping must never create an empty interval.
assert.equal(zoomForFit(0.4, 'cover'), 1);
assert.equal(zoomForFit(0.4, 'contain'), 0.4);
assert.equal(zoomForFit(0.1, 'contain'), 0.25);
assert.equal(zoomForFit(8, 'cover'), 4);
assert.equal(zoomForFit(NaN, 'cover'), 1);
const previousFrame = {fit:'cover',presentation:'plain',zoom:3,pan_x:0.6,pan_y:-0.3,view_distance_mm:780};
const standeeFrame = frameForMode(previousFrame, 'contain');
assert.deepEqual(standeeFrame, {fit:'contain',presentation:'standee',zoom:1,pan_x:0,pan_y:0,view_distance_mm:780});
assert.equal(previousFrame.zoom, 3);
assert.deepEqual(frameForMode({...standeeFrame,zoom:2,pan_x:-0.4,pan_y:0.5}, 'cover'), {fit:'cover',presentation:'plain',zoom:1,pan_x:0,pan_y:0,view_distance_mm:780});
// The exact source-UV domain supplied for the PNG must map to its lower/upper corners.
for (const aspect of [16/9, 9/16, 1]) {
  const [offsetU, offsetV, width, height] = decorationDomain(aspect);
  assert.ok(Math.abs((-0.15/aspect + offsetU) / width) < 1e-12);
  assert.ok(Math.abs((1+0.15/aspect + offsetU) / width - 1) < 1e-12);
  assert.equal((-0.30 + offsetV) / height, 0);
  assert.ok(Math.abs((1.14 + offsetV) / height - 1) < 1e-12);
}
